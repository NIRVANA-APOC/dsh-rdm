// Build the two JavaScript artifacts of the dsh-rdm plugin:
//   lib/index.js  — Host half (ESM, Node 20+, DSH packages stay external)
//   lib/client.js — browser half in the DSH module-loader format
// Usage: node scripts/build.mjs
import { build } from 'esbuild'
import fs from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const libDir = path.join(root, 'lib')
// `--host-only` / `--client-only` let two owners build their halves in
// parallel without deleting the other half's artifact (0.2.0 workstreams).
const hostOnly = process.argv.includes('--host-only')
const clientOnly = process.argv.includes('--client-only')
const buildHost = !clientOnly
const buildClient = !hostOnly

await fs.mkdir(libDir, { recursive: true })

// ── Host half ────────────────────────────────────────────────────────────────
// dsh-client packages resolve from the DSH installation at runtime; they must
// stay external so esbuild does not try to bundle the Harness.
if (buildHost) {
await build({
  entryPoints: [path.join(root, 'src/index.ts')],
  outfile: path.join(libDir, 'index.js'),
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  external: ['node:*'],
  alias: {
    // The host bundle is self-contained: a linked local plugin cannot resolve
    // Harness packages from the profile, so the config schema library is
    // vendored and bundled (../vendor, extracted from the DSH installation).
    '@deepseek-ai/schemastery': path.join(root, 'vendor', 'schemastery.mjs'),
    '@deepseek-ai/cosmokit': path.join(root, 'vendor', 'cosmokit.mjs'),
  },
  sourcemap: false,
  legalComments: 'none',
  logLevel: 'info',
  banner: { js: '// generated by dsh-rdm/scripts/build.mjs — do not edit' },
})
}

// ── Client half ──────────────────────────────────────────────────────────────
// Compiled to CommonJS and wrapped in the module-loader factory so `require`
// (React and other baseline modules) comes from the page's module table.
if (buildClient) {
const client = await build({
  entryPoints: [path.join(root, 'src/client/index.tsx')],
  bundle: true,
  platform: 'browser',
  format: 'cjs',
  target: 'es2020',
  external: ['react', 'react-dom', 'react/jsx-runtime'],
  jsx: 'transform',
  jsxFactory: 'React.createElement',
  jsxFragment: 'React.Fragment',
  loader: { '.tsx': 'tsx', '.ts': 'ts' },
  write: false,
  legalComments: 'none',
  logLevel: 'info',
})
const code = client.outputFiles[0].text
const wrapped = `// generated by dsh-rdm/scripts/build.mjs — do not edit
window.__ModuleLoader__.load({
  id: 'dsh-rdm',
  factory(require) {
    const module = { exports: {} };
    const exports = module.exports;
    (function (module, exports, require) {
${code}
    })(module, module.exports, require);
    return module.exports;
  },
});
`
await fs.writeFile(path.join(libDir, 'client.js'), wrapped)
}
console.log(`[dsh-rdm] built ${[buildHost ? 'lib/index.js' : '', buildClient ? 'lib/client.js' : ''].filter(Boolean).join(' and ')}`)
