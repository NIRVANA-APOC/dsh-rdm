#!/usr/bin/env bash
# Sandbox-safe build entry point for dsh-rdm.
#
# Why this exists: inside the DSH agent sandbox a Node script cannot spawn
# child processes (child_process => EPERM), so `scripts/build.mjs` /
# `scripts/build-kernel.mjs` only work outside the sandbox. This script runs
# the same builds from a shell, where process creation is permitted.
#
# Usage: bash scripts/dev-build.sh [host|client|all|kernel]
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

case "$(uname -s)" in
  MINGW*|MSYS*|CYGWIN*) OS=win32 ;;
  Darwin) OS=darwin ;;
  Linux) OS=linux ;;
  *) echo "dev-build: unsupported OS $(uname -s)" >&2; exit 1 ;;
esac
case "$(uname -m)" in
  x86_64|amd64) ARCH=x64 ;;
  aarch64|arm64) ARCH=arm64 ;;
  *) ARCH="$(uname -m)" ;;
esac

ESBUILD="$ROOT/node_modules/@esbuild/$OS-$ARCH/esbuild.exe"
[ -x "$ESBUILD" ] || ESBUILD="$ROOT/node_modules/@esbuild/$OS-$ARCH/esbuild"
# npm places the platform binary under `bin/`; pnpm hoists it to the package root.
[ -x "$ESBUILD" ] || ESBUILD="$ROOT/node_modules/@esbuild/$OS-$ARCH/bin/esbuild.exe"
[ -x "$ESBUILD" ] || ESBUILD="$ROOT/node_modules/@esbuild/$OS-$ARCH/bin/esbuild"
[ -x "$ESBUILD" ] || { echo "dev-build: esbuild binary not found for $OS-$ARCH" >&2; exit 1; }

# Native tools on Windows need Windows-style paths; MSYS passes /c/... through
# to them unexpanded in some positions (esbuild --alias, cargo TMP).
if [ "$OS" = win32 ]; then
  ROOT_NATIVE="$(cygpath -w "$ROOT" 2>/dev/null || echo "$ROOT")"
else
  ROOT_NATIVE="$ROOT"
fi

mkdir -p lib .tmp

build_host() {
  echo "[dev-build] host -> lib/index.js"
  local version
  version=$(node -p "require('./package.json').version")
  "$ESBUILD" src/index.ts \
    --bundle --platform=node --format=esm --target=node20 \
    --external:node:* \
    --alias:@deepseek-ai/schemastery="$ROOT_NATIVE/vendor/schemastery.mjs" \
    --alias:@deepseek-ai/cosmokit="$ROOT_NATIVE/vendor/cosmokit.mjs" \
    --define:__DSH_RDM_VERSION__="\"$version\"" \
    --banner:js='// generated by dsh-rdm/scripts/build.mjs — do not edit' \
    --legal-comments=none \
    --outfile=lib/index.js
}

build_client() {
  echo "[dev-build] client -> lib/client.js"
  "$ESBUILD" src/client/index.tsx \
    --bundle --platform=browser --format=cjs --target=es2020 \
    --external:react --external:react-dom --external:react/jsx-runtime \
    --jsx=transform --jsx-factory=React.createElement --jsx-fragment=React.Fragment \
    --loader:.tsx=tsx --loader:.ts=ts \
    --legal-comments=none \
    --outfile=.tmp/client.body.js
  node scripts/dev-wrap-client.mjs
}

build_kernel() {
  echo "[dev-build] kernel -> bin/$OS-$ARCH/rdm-kernel"
  local cargo_bin="$HOME/.cargo/bin"
  local mingw_bin=""
  local packages="${LOCALAPPDATA:-$HOME/AppData/Local}/Microsoft/WinGet/Packages"
  if [ -d "$packages" ]; then
    for dir in "$packages"/BrechtSanders.WinLibs*; do
      if [ -x "$dir/mingw64/bin/gcc.exe" ]; then mingw_bin="$dir/mingw64/bin"; fi
    done
  fi
  mkdir -p kernel/target/tmp
  local kernel_native
  kernel_native="$(cd kernel && cygpath -w "$(pwd)" 2>/dev/null || pwd)"
  (
    cd kernel
    export PATH="$mingw_bin:$cargo_bin:$PATH"
    export TMP="$kernel_native/target/tmp"
    export TEMP="$kernel_native/target/tmp"
    cargo build --release
  )
  local exe_name="rdm-kernel"
  [ "$OS" = win32 ] && exe_name="rdm-kernel.exe"
  mkdir -p "bin/$OS-$ARCH"
  local dest="bin/$OS-$ARCH/$exe_name"
  if ! cp "kernel/target/release/$exe_name" "$dest" 2>/dev/null; then
    mv "$dest" "$dest.old-$(date +%s)" 2>/dev/null || true
    cp "kernel/target/release/$exe_name" "$dest"
    echo "[dev-build] previous kernel moved aside; restart the plugin kernel to load the new build"
  fi
  ls -la "$dest"
}

case "${1:-all}" in
  host) build_host ;;
  client) build_client ;;
  kernel) build_kernel ;;
  all) build_host; build_client ;;
  *) echo "usage: bash scripts/dev-build.sh [host|client|all|kernel]" >&2; exit 2 ;;
esac
echo "[dev-build] done"
