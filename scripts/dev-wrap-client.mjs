// Wrap the esbuild client body in the Harness module-loader factory.
// Pure filesystem work (no child processes) so it also runs inside the DSH
// sandbox, where scripts/build.mjs cannot spawn esbuild.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const bodyPath = path.join(root, '.tmp', 'client.body.js')
const outPath = path.join(root, 'lib', 'client.js')
const code = fs.readFileSync(bodyPath, 'utf8')
const wrapped = `// generated by dsh-rdm/scripts/build.mjs — do not edit
window.__ModuleLoader__.load({
  id: 'dsh-rdm',
  factory(require) {
    const module = { exports: {} };
    const exports = module.exports;
    (function (module, exports, require) {
${code}
    })(module, module.exports, require);
    return module.exports;
  },
});
`
fs.mkdirSync(path.dirname(outPath), { recursive: true })
fs.writeFileSync(outPath, wrapped)
console.log(`[dev-build] wrapped ${code.length} bytes -> lib/client.js`)
